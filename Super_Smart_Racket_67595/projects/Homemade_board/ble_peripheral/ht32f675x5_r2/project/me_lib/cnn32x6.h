bool cnn32x6_stream_push(const int16_t s[CNN32X6_IN_W], cnn32x6_result_t *out);

/** @brief 開機以來累計偵測到的揮拍次數。 */
uint32_t cnn32x6_stream_swing_count(void);

/* 上板排查用的統計。漏判時第一件要分清楚的事是「根本沒觸發」還是「觸發了但被
   判成非揮拍」——這兩者的處理方式完全不同:

     triggers 沒有增加   -> 活動量沒過門檻, 調 CNN32X6_TRIG_LEVEL
                            (也要先確認感測器安裝方向跟訓練資料一致)
     triggers 增加但 rejected 也增加
                        -> 有抓到動作但模型不認, 多半是視窗對齊或安裝方向的問題,
                           可以先試著把 CNN32X6_ALIGN_SEARCH 調大
     swings 有增加       -> 辨識鏈路正常, 問題在後面 (BLE / App) */
typedef struct {
    uint32_t triggers;       /* 觸發並實際跑過推論的次數 (含被丟掉的) */
    uint32_t rejected;       /* 其中被判成 CNN32X6_CLASS_NONE 而丟掉的  */
    uint32_t returns;        /* 被方向判別當成「收拍」丟掉的次數        */
    uint32_t swings;         /* 真正算數的揮拍數, 等同 swing_count      */
    int32_t  last_peak_act;  /* 最後一次觸發時的峰值活動量              */
    uint8_t  last_label;     /* 最後一次觸發的判定結果 (可能是 6)       */
} cnn32x6_stats_t;

void cnn32x6_get_stats(cnn32x6_stats_t *out);

